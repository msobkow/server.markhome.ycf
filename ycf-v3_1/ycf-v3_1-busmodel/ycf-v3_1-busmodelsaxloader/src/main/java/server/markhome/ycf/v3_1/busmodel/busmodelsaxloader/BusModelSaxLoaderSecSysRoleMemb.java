/*
 *	BusModelSaxLoaderSecSysRoleMembParse XML SAX Element Handler implementation
 *	for SecSysRoleMemb.
 */
public class BusModelSaxLoaderSecSysRoleMemb
	extends YCFLibXmlCoreElementHandler
{
	public BusModelSaxLoaderSecSysRoleMemb( BusModelSaxLoader saxLoader ) {
		super( saxLoader );
	}

	public void startElement(
		String		uri,
		String		localName,
		String		qName,
		Attributes	attrs )
	throws SAXException
	{
		final String S_ProcName = "startElement";
		IBusModelSecSysRoleMembObj origBuff = null;
		IBusModelSecSysRoleMembEditObj editBuff = null;
		// Common XML Attributes
		String attrId = null;
		// SecSysRoleMemb Attributes
		String attrUser = null;
		// SecSysRoleMemb References
		IBusModelSecSysRoleObj refSysRole = null;
		IBusModelSecUserObj refUser = null;
		// Attribute Extraction
		String attrLocalName;
		int numAttrs;
		int idxAttr;
		final String S_LocalName = "LocalName";
		try {
			assert qName.equals( "SecSysRoleMemb" );

			BusModelSaxLoader saxLoader = (BusModelSaxLoader)getParser();
			if( saxLoader == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser()" );
			}

			IBusModelSchemaObj schemaObj = saxLoader.getSchemaObj();
			if( schemaObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser().getSchemaObj()" );
			}

			// Instantiate an edit buffer for the parsed information
			origBuff = (IBusModelSecSysRoleMembObj)schemaObj.getSecSysRoleMembTableObj().newInstance();
			editBuff = (IBusModelSecSysRoleMembEditObj)origBuff.beginEdit();

			// Extract Attributes
			numAttrs = attrs.getLength();
			for( idxAttr = 0; idxAttr < numAttrs; idxAttr++ ) {
				attrLocalName = attrs.getLocalName( idxAttr );
				if( attrLocalName.equals( "Id" ) ) {
					if( attrId != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrId = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "User" ) ) {
					if( attrUser != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrUser = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "schemaLocation" ) ) {
					// ignored
				}
				else {
					throw new YCFLibUnrecognizedAttributeException( getClass(),
						S_ProcName,
						getParser().getLocationInfo(),
						attrLocalName );
				}
			}

			// Ensure that required attributes have values
			if( ( attrUser == null ) || ( attrUser.length() <= 0 ) ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"User" );
			}

			// Save named attributes to context
			YCFLibXmlCoreContext curContext = getParser().getCurContext();
			curContext.putNamedValue( "Id", attrId );
			curContext.putNamedValue( "User", attrUser );

			// Convert string attributes to native Java types
			// and apply the converted attributes to the editBuff.

			Integer natId;
			if( ( attrId != null ) && ( attrId.length() > 0 ) ) {
				natId = Integer.valueOf( Integer.parseInt( attrId ) );
			}
			else {
				natId = null;
			}
			// Get the scope/container object

			YCFLibXmlCoreContext parentContext = curContext.getPrevContext();
			Object scopeObj;
			if( parentContext != null ) {
				scopeObj = parentContext.getNamedValue( "Object" );
			}
			else {
				scopeObj = null;
			}

			// Resolve and apply required Container reference

			if( scopeObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"scopeObj" );
			}
			else if( scopeObj instanceof IBusModelSecSysRoleObj ) {
				refSysRole = (IBusModelSecSysRoleObj) scopeObj;
				editBuff.setRequiredContainerSysRole( refSysRole );
			}
			else {
				throw new YCFLibUnsupportedClassException( getClass(),
					S_ProcName,
					"scopeObj",
					scopeObj,
					"IBusModelSecSysRoleObj" );
			}

			// Lookup refUser by key name value attr
			if( ( attrUser != null ) && ( attrUser.length() > 0 ) ) {
				refUser = (IBusModelSecUserObj)schemaObj.getSecUserTableObj().readSecUserByULoginIdx( attrUser );
				if( refUser == null ) {
					throw new YCFLibNullArgumentException( getClass(),
						S_ProcName,
						0,
						"Resolve User reference named \"" + attrUser + "\" to table SecUser" );
				}
			}
			else {
				refUser = null;
			}
			editBuff.setRequiredParentUser( refUser );

			BusModelSaxLoader.LoaderBehaviourEnum loaderBehaviour = saxLoader.getSecSysRoleMembLoaderBehaviour();
			IBusModelSecSysRoleMembEditObj editSecSysRoleMemb = null;
			IBusModelSecSysRoleMembObj origSecSysRoleMemb = (IBusModelSecSysRoleMembObj)schemaObj.getSecSysRoleMembTableObj().readSecSysRoleMembByIdIdx( refSysRole.getRequiredSecSysRoleId(),
			refUser.getRequiredLoginId() );
			if( origSecSysRoleMemb == null ) {
				editSecSysRoleMemb = editBuff;
			}
			else {
				switch( loaderBehaviour ) {
					case Insert:
						break;
					case Update:
						editSecSysRoleMemb = (IBusModelSecSysRoleMembEditObj)origSecSysRoleMemb.beginEdit();
						editSecSysRoleMemb.setRequiredParentUser( editBuff.getRequiredParentUser() );
						break;
					case Replace:
						editSecSysRoleMemb = (IBusModelSecSysRoleMembEditObj)origSecSysRoleMemb.beginEdit();
						editSecSysRoleMemb.deleteInstance();
						editSecSysRoleMemb = null;
						origSecSysRoleMemb = null;
						editSecSysRoleMemb = editBuff;
						break;
				}
			}

			if( editSecSysRoleMemb != null ) {
				if( origSecSysRoleMemb != null ) {
					editSecSysRoleMemb.update();
				}
				else {
					origSecSysRoleMemb = (IBusModelSecSysRoleMembObj)editSecSysRoleMemb.create();
				}
				editSecSysRoleMemb = null;
			}

			curContext.putNamedValue( "Object", origSecSysRoleMemb );
		}
		catch( RuntimeException e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage(),
				e );
		}
		catch( Error e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage() );
		}
	}

	public void endElement(
		String		uri,
		String		localName,
		String		qName )
	throws SAXException
	{
	}
}

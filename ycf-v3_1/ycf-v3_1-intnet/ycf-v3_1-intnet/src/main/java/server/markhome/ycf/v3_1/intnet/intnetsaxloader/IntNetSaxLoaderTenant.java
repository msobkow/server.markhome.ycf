/*
 *	IntNetSaxLoaderTenantParse XML SAX Element Handler implementation
 *	for Tenant.
 */
public class IntNetSaxLoaderTenant
	extends YCFLibXmlCoreElementHandler
{
	public IntNetSaxLoaderTenant( IntNetSaxLoader saxLoader ) {
		super( saxLoader );
	}

	public void startElement(
		String		uri,
		String		localName,
		String		qName,
		Attributes	attrs )
	throws SAXException
	{
		final String S_ProcName = "startElement";
		try {
			assert qName.equals( "Tenant" );

			IntNetSaxLoader saxLoader = (IntNetSaxLoader)getParser();
			if( saxLoader == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser()" );
			}

			IIntNetSchemaObj schemaObj = saxLoader.getSchemaObj();
			if( schemaObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser().getSchemaObj()" );
			}

			YCFLibXmlCoreContext curContext = getParser().getCurContext();

			ISecureTenantObj useTenant = saxLoader.getUseTenant();
			if( useTenant == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"saxLoader.useTenant" );
			}

			curContext.putNamedValue( "Object", useTenant );
		}
		catch( RuntimeException e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage(),
				e );
		}
		catch( Error e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage() );
		}
	}

	public void endElement(
		String		uri,
		String		localName,
		String		qName )
	throws SAXException
	{
	}
}

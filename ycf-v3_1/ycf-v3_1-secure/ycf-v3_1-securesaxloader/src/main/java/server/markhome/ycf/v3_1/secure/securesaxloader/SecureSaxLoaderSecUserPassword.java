/*
 *	SecureSaxLoaderSecUserPasswordParse XML SAX Element Handler implementation
 *	for SecUserPassword.
 */
public class SecureSaxLoaderSecUserPassword
	extends YCFLibXmlCoreElementHandler
{
	public SecureSaxLoaderSecUserPassword( SecureSaxLoader saxLoader ) {
		super( saxLoader );
	}

	public void startElement(
		String		uri,
		String		localName,
		String		qName,
		Attributes	attrs )
	throws SAXException
	{
		final String S_ProcName = "startElement";
		ISecureSecUserPasswordObj origBuff = null;
		ISecureSecUserPasswordEditObj editBuff = null;
		// Common XML Attributes
		String attrId = null;
		// SecUserPassword Attributes
		String attrPWSetStamp = null;
		String attrPasswordHash = null;
		// SecUserPassword References
		ISecureSecUserObj refUser = null;
		// Attribute Extraction
		String attrLocalName;
		int numAttrs;
		int idxAttr;
		final String S_LocalName = "LocalName";
		try {
			assert qName.equals( "SecUserPassword" );

			SecureSaxLoader saxLoader = (SecureSaxLoader)getParser();
			if( saxLoader == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser()" );
			}

			ISecureSchemaObj schemaObj = saxLoader.getSchemaObj();
			if( schemaObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser().getSchemaObj()" );
			}

			// Instantiate an edit buffer for the parsed information
			origBuff = (ISecureSecUserPasswordObj)schemaObj.getSecUserPasswordTableObj().newInstance();
			editBuff = (ISecureSecUserPasswordEditObj)origBuff.beginEdit();

			// Extract Attributes
			numAttrs = attrs.getLength();
			for( idxAttr = 0; idxAttr < numAttrs; idxAttr++ ) {
				attrLocalName = attrs.getLocalName( idxAttr );
				if( attrLocalName.equals( "Id" ) ) {
					if( attrId != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrId = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "PWSetStamp" ) ) {
					if( attrPWSetStamp != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrPWSetStamp = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "PasswordHash" ) ) {
					if( attrPasswordHash != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrPasswordHash = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "schemaLocation" ) ) {
					// ignored
				}
				else {
					throw new YCFLibUnrecognizedAttributeException( getClass(),
						S_ProcName,
						getParser().getLocationInfo(),
						attrLocalName );
				}
			}

			// Ensure that required attributes have values
			if( ( attrPWSetStamp == null ) || ( attrPWSetStamp.length() <= 0 ) ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"PWSetStamp" );
			}
			if( attrPasswordHash == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"PasswordHash" );
			}

			// Save named attributes to context
			YCFLibXmlCoreContext curContext = getParser().getCurContext();
			curContext.putNamedValue( "Id", attrId );
			curContext.putNamedValue( "PWSetStamp", attrPWSetStamp );
			curContext.putNamedValue( "PasswordHash", attrPasswordHash );

			// Convert string attributes to native Java types
			// and apply the converted attributes to the editBuff.

			Integer natId;
			if( ( attrId != null ) && ( attrId.length() > 0 ) ) {
				natId = Integer.valueOf( Integer.parseInt( attrId ) );
			}
			else {
				natId = null;
			}
			LocalDateTime natPWSetStamp;
			try {
				natPWSetStamp = YCFLibXmlUtil.parseTimestamp( attrPWSetStamp );
			}
			catch( RuntimeException e ) {
				throw new YCFLibInvalidArgumentException( getClass(),
					S_ProcName,
					0,
					"PWSetStamp",
					e );
			}
			editBuff.setRequiredPWSetStamp( natPWSetStamp );

			String natPasswordHash = attrPasswordHash;
			editBuff.setRequiredPasswordHash( natPasswordHash );

			// Get the scope/container object

			YCFLibXmlCoreContext parentContext = curContext.getPrevContext();
			Object scopeObj;
			if( parentContext != null ) {
				scopeObj = parentContext.getNamedValue( "Object" );
			}
			else {
				scopeObj = null;
			}

			// Resolve and apply required Container reference

			if( scopeObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"scopeObj" );
			}
			else if( scopeObj instanceof ISecureSecUserObj ) {
				refUser = (ISecureSecUserObj) scopeObj;
				editBuff.setRequiredContainerUser( refUser );
			}
			else {
				throw new YCFLibUnsupportedClassException( getClass(),
					S_ProcName,
					"scopeObj",
					scopeObj,
					"ISecureSecUserObj" );
			}

			ISecureSecUserPasswordObj origSecUserPassword;
			ISecureSecUserPasswordEditObj editSecUserPassword = editBuff;
			origSecUserPassword = (ISecureSecUserPasswordObj)editSecUserPassword.create();
			editSecUserPassword = null;

			curContext.putNamedValue( "Object", origSecUserPassword );
		}
		catch( RuntimeException e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage(),
				e );
		}
		catch( Error e ) {
			throw new SAXException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getName() + " - " + e.getMessage() );
		}
	}

	public void endElement(
		String		uri,
		String		localName,
		String		qName )
	throws SAXException
	{
	}
}
